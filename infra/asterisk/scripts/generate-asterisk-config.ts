import Database from "better-sqlite3";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const CONFIG_DIR = resolve(import.meta.dirname, "../config");
const DB_PATH = process.env.DATABASE_URL?.replace("file:", "") || resolve(import.meta.dirname, "../../../services/api/dev.db");

interface SipRow {
  extension: string;
  username: string;
  plaintextPassword: string | null;
  passwordHashOrEncrypted: string;
  memberId: string;
  displayName: string;
  kind: string;
  familyId: string;
}

interface AllowedCallRow {
  fromMemberId: string;
  fromExtension: string;
  toMemberId: string;
  toExtension: string;
  enabled: number;
}

function generate() {
  if (!existsSync(DB_PATH)) {
    console.error(`Database not found at ${DB_PATH}`);
    process.exit(1);
  }

  const db = new Database(DB_PATH);

  // Get all SIP accounts with member info
  const accounts = db.prepare(`
    SELECT sa.extension, sa.username, sa.plaintext_password as plaintextPassword,
           sa.password_hash_or_encrypted as passwordHashOrEncrypted,
           fm.id as memberId, fm.display_name as displayName,
           fm.kind, fm.family_id as familyId
    FROM sip_account sa
    JOIN family_member fm ON fm.id = sa.family_member_id
    WHERE sa.enabled = 1 AND fm.active = 1
  `).all() as SipRow[];

  if (accounts.length === 0) {
    console.log("No active SIP accounts found.");
    db.close();
    return;
  }

  // Get all allowed calls
  const callRules = db.prepare(`
    SELECT ac.from_member_id as fromMemberId, fromSa.extension as fromExtension,
           ac.to_member_id as toMemberId, toSa.extension as toExtension,
           ac.enabled
    FROM allowed_call ac
    JOIN sip_account fromSa ON fromSa.family_member_id = ac.from_member_id
    JOIN sip_account toSa ON toSa.family_member_id = ac.to_member_id
    WHERE ac.enabled = 1
  `).all() as AllowedCallRow[];

  // Build lookup by memberId
  const sipByMember = new Map(accounts.map((a) => [a.memberId, a]));

  // Generate pjsip.generated.conf
  let pjsipLines = "; Generated by Telefoninho - do not edit directly\n";
  pjsipLines += "; Generated at " + new Date().toISOString() + "\n\n";

  for (const acc of accounts) {
    const pass = acc.plaintextPassword || acc.passwordHashOrEncrypted;
    pjsipLines += `[${acc.extension}]\n`;
    pjsipLines += `type=endpoint\n`;
    pjsipLines += `context=ctx-member-${acc.extension}\n`;
    pjsipLines += `disallow=all\n`;
    pjsipLines += `allow=opus,ulaw,alaw\n`;
    pjsipLines += `auth=auth${acc.extension}\n`;
    pjsipLines += `aors=${acc.extension}\n`;
    pjsipLines += `direct_media=no\n`;
    pjsipLines += `rtp_symmetric=yes\n`;
    pjsipLines += `force_rport=yes\n`;
    pjsipLines += `rewrite_contact=yes\n`;
    pjsipLines += `callerid="${acc.displayName}" <${acc.extension}>\n\n`;

    pjsipLines += `[auth${acc.extension}]\n`;
    pjsipLines += `type=auth\n`;
    pjsipLines += `auth_type=userpass\n`;
    pjsipLines += `username=${acc.username}\n`;
    pjsipLines += `password=${pass}\n\n`;

    pjsipLines += `[${acc.extension}]\n`;
    pjsipLines += `type=aor\n`;
    pjsipLines += `max_contacts=1\n`;
    pjsipLines += `remove_existing=yes\n`;
    pjsipLines += `remove_unavailable=yes\n\n`;
  }

  writeFileSync(resolve(CONFIG_DIR, "pjsip.generated.conf"), pjsipLines);

  // Build allowed destinations by from-extension
  const dialplanByExtension = new Map<string, string[]>();
  for (const rule of callRules) {
    if (!rule.enabled) continue;
    const existing = dialplanByExtension.get(rule.fromExtension) || [];
    existing.push(rule.toExtension);
    dialplanByExtension.set(rule.fromExtension, existing);
  }

  // Also ensure all accounts can receive calls (add inbound context)
  const inboundByExtension = new Map<string, string[]>();
  for (const rule of callRules) {
    if (!rule.enabled) continue;
    const existing = inboundByExtension.get(rule.toExtension) || [];
    if (!existing.includes(rule.fromExtension)) {
      existing.push(rule.fromExtension);
    }
    inboundByExtension.set(rule.toExtension, existing);
  }

  // Generate extensions.generated.conf
  let extLines = "; Generated by Telefoninho - do not edit directly\n";
  extLines += "; Generated at " + new Date().toISOString() + "\n\n";

  // Default blocked context
  extLines += "[blocked]\n";
  extLines += "exten => s,1,Answer()\n";
  extLines += " same => n,Playback(vm-goodbye)\n";
  extLines += " same => n,Hangup()\n\n";

  for (const [ext, targets] of dialplanByExtension) {
    extLines += `; ${sipByMember.get(ext)?.displayName || ext}\n`;
    extLines += `[ctx-member-${ext}]\n`;

    for (const target of targets) {
      extLines += `exten => ${target},1,Dial(PJSIP/${target},30)\n`;
      extLines += ` same => n,Hangup()\n`;
    }
    extLines += `exten => _X.,1,Goto(blocked,s,1)\n\n`;
  }

  // For extensions without outgoing rules, create empty blocking context
  for (const acc of accounts) {
    if (!dialplanByExtension.has(acc.extension)) {
      extLines += `; ${acc.displayName} - no allowed destinations (blocked)\n`;
      extLines += `[ctx-member-${acc.extension}]\n`;
      extLines += `exten => _X.,1,Goto(blocked,s,1)\n\n`;
    }
  }

  writeFileSync(resolve(CONFIG_DIR, "extensions.generated.conf"), extLines);

  console.log(`✓ Generated configs for ${accounts.length} SIP accounts`);
  console.log(`  → pjsip.generated.conf`);
  console.log(`  → extensions.generated.conf`);

  db.close();
}

generate();
