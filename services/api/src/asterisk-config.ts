import Database from "better-sqlite3";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

type SipRow = {
  extension: string;
  username: string;
  plaintextPassword: string | null;
  passwordHashOrEncrypted: string;
  memberId: string;
  displayName: string;
  kind: string;
  familyId: string;
};

type AllowedCallRow = {
  fromMemberId: string;
  fromExtension: string;
  toMemberId: string;
  toExtension: string;
  enabled: number;
};

export type AsteriskGenerationResult = {
  generatedAccounts: number;
  generatedAt: Date;
  pjsipPath: string;
  extensionsPath: string;
};

function getDatabasePath(databaseUrl = process.env.DATABASE_URL): string {
  return (databaseUrl || "file:./dev.db").replace("file:", "");
}

function getConfigDir(): string {
  return process.env.ASTERISK_CONFIG_DIR || resolve(import.meta.dirname, "../../../infra/asterisk/config");
}

export function generateAsteriskConfig(options: {
  databaseUrl?: string;
  configDir?: string;
} = {}): AsteriskGenerationResult {
  const dbPath = getDatabasePath(options.databaseUrl);
  const configDir = options.configDir || getConfigDir();

  if (!existsSync(dbPath)) {
    throw new Error(`Database not found at ${dbPath}`);
  }

  mkdirSync(configDir, { recursive: true });

  const sqlite = new Database(dbPath);
  try {
    const accounts = sqlite.prepare(`
      SELECT sa.extension, sa.username, sa.plaintext_password as plaintextPassword,
             sa.password_hash_or_encrypted as passwordHashOrEncrypted,
             fm.id as memberId, fm.display_name as displayName,
             fm.kind, fm.family_id as familyId
      FROM sip_account sa
      JOIN family_member fm ON fm.id = sa.family_member_id
      WHERE sa.enabled = 1 AND fm.active = 1
    `).all() as SipRow[];

    const callRules = sqlite.prepare(`
      SELECT ac.from_member_id as fromMemberId, fromSa.extension as fromExtension,
             ac.to_member_id as toMemberId, toSa.extension as toExtension,
             ac.enabled
      FROM allowed_call ac
      JOIN sip_account fromSa ON fromSa.family_member_id = ac.from_member_id
      JOIN sip_account toSa ON toSa.family_member_id = ac.to_member_id
      WHERE ac.enabled = 1
    `).all() as AllowedCallRow[];

    const generatedAt = new Date();
    const pjsipPath = resolve(configDir, "pjsip.generated.conf");
    const extensionsPath = resolve(configDir, "extensions.generated.conf");

    writeFileSync(pjsipPath, buildPjsipConfig(accounts, generatedAt));
    writeFileSync(extensionsPath, buildExtensionsConfig(accounts, callRules, generatedAt));

    return {
      generatedAccounts: accounts.length,
      generatedAt,
      pjsipPath,
      extensionsPath,
    };
  } finally {
    sqlite.close();
  }
}

function buildPjsipConfig(accounts: SipRow[], generatedAt: Date): string {
  const lines: string[] = [
    "; Generated by Telefoninho - do not edit directly",
    `; Generated at ${generatedAt.toISOString()}`,
    "",
  ];

  for (const acc of accounts) {
    const pass = acc.plaintextPassword || acc.passwordHashOrEncrypted;
    lines.push(
      `[${acc.extension}]`,
      "type=endpoint",
      `context=ctx-member-${acc.extension}`,
      "disallow=all",
      "allow=opus,ulaw,alaw",
      `auth=auth${acc.extension}`,
      `aors=${acc.extension}`,
      "direct_media=no",
      "rtp_symmetric=yes",
      "force_rport=yes",
      "rewrite_contact=yes",
      `callerid="${acc.displayName}" <${acc.extension}>`,
      "",
      `[auth${acc.extension}]`,
      "type=auth",
      "auth_type=userpass",
      `username=${acc.username}`,
      `password=${pass}`,
      "",
      `[${acc.extension}]`,
      "type=aor",
      "max_contacts=1",
      "remove_existing=yes",
      "remove_unavailable=yes",
      "",
    );
  }

  return `${lines.join("\n")}\n`;
}

function buildExtensionsConfig(accounts: SipRow[], callRules: AllowedCallRow[], generatedAt: Date): string {
  const sipByExtension = new Map(accounts.map((account) => [account.extension, account]));
  const dialplanByExtension = new Map<string, string[]>();

  for (const rule of callRules) {
    if (!rule.enabled) continue;
    const existing = dialplanByExtension.get(rule.fromExtension) || [];
    existing.push(rule.toExtension);
    dialplanByExtension.set(rule.fromExtension, existing);
  }

  const lines: string[] = [
    "; Generated by Telefoninho - do not edit directly",
    `; Generated at ${generatedAt.toISOString()}`,
    "",
    "[blocked]",
    "exten => s,1,Answer()",
    " same => n,Playback(vm-goodbye)",
    " same => n,Hangup()",
    "",
  ];

  for (const [extension, targets] of dialplanByExtension) {
    lines.push(`; ${sipByExtension.get(extension)?.displayName || extension}`, `[ctx-member-${extension}]`);
    for (const target of targets) {
      lines.push(`exten => ${target},1,Dial(PJSIP/${target},30)`, " same => n,Hangup()");
    }
    lines.push("exten => _X.,1,Goto(blocked,s,1)", "");
  }

  for (const account of accounts) {
    if (dialplanByExtension.has(account.extension)) continue;
    lines.push(
      `; ${account.displayName} - no allowed destinations (blocked)`,
      `[ctx-member-${account.extension}]`,
      "exten => _X.,1,Goto(blocked,s,1)",
      "",
    );
  }

  return `${lines.join("\n")}\n`;
}
